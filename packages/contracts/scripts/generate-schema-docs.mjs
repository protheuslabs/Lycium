#!/usr/bin/env node
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const repoRoot = resolve(packageRoot, "../..");
const schemasDir = join(packageRoot, "schemas");
const fixturesDir = join(packageRoot, "fixtures");
const docsPath = join(repoRoot, "docs", "contracts", "schema-reference.md");
const packageJson = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));

const fixtureBySchema = new Map([
  ["lycium-course.schema.json", "valid-course.json"],
  ["lycium-source-record.schema.json", null],
  ["lycium-progress.schema.json", "valid-progress.json"],
  ["lycium-quiz-progress.schema.json", "valid-quiz-progress.json"],
  ["lycium-course-quality-report.schema.json", "valid-course-quality-report.json"],
  ["lycium-course-lifecycle.schema.json", "valid-course-lifecycle.json"],
  ["lycium-generation-job.schema.json", "valid-generation-job.json"],
  ["lycium-curriculum-benchmark.schema.json", "valid-curriculum-benchmark.json"],
  ["lycium-program.schema.json", "full-stack-engineer-program.json"],
  ["lycium-provider-settings.schema.json", "valid-provider-settings.json"],
]);

function exportedSchemaPaths() {
  const exportsMap = packageJson.exports ?? {};
  return new Set(
    Object.keys(exportsMap)
      .filter((key) => key.startsWith("./schemas/") && key.endsWith(".schema.json"))
      .map((key) => key.replace("./schemas/", "")),
  );
}

function schemaType(schema) {
  if (Array.isArray(schema.type)) return schema.type.join(" | ");
  if (typeof schema.type === "string") return schema.type;
  if (schema.enum) return `enum(${schema.enum.map(String).join(", ")})`;
  if (schema.oneOf) return "oneOf";
  if (schema.anyOf) return "anyOf";
  if (schema.$ref) return schema.$ref;
  return "unspecified";
}

function formatList(values) {
  return values.length ? values.map((value) => `\`${value}\``).join(", ") : "_None_";
}

function topLevelProperties(schema) {
  const properties = schema.properties ?? {};
  return Object.entries(properties)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, property]) => {
      const required = (schema.required ?? []).includes(name) ? "required" : "optional";
      return `| \`${name}\` | ${schemaType(property)} | ${required} |`;
    });
}

function docForSchema(filename, exportedSchemas) {
  const schema = JSON.parse(readFileSync(join(schemasDir, filename), "utf8"));
  const fixture = fixtureBySchema.get(filename);
  const exported = exportedSchemas.has(filename) ? "Yes" : "No";
  const properties = topLevelProperties(schema);
  return [
    `## ${schema.title ?? filename}`,
    "",
    `- Schema file: \`${relative(repoRoot, join(schemasDir, filename))}\``,
    `- Public export: ${exported}`,
    `- JSON Schema ID: \`${schema.$id ?? "not declared"}\``,
    `- Root type: \`${schemaType(schema)}\``,
    `- Required root fields: ${formatList(schema.required ?? [])}`,
    fixture ? `- Example fixture: \`${relative(repoRoot, join(fixturesDir, fixture))}\`` : "- Example fixture: _None yet_",
    "",
    "### Top-level properties",
    "",
    "| Property | Type | Required |",
    "| --- | --- | --- |",
    ...(properties.length ? properties : ["| _None declared_ | _n/a_ | _n/a_ |"]),
    "",
  ].join("\n");
}

function generateMarkdown() {
  const exportedSchemas = exportedSchemaPaths();
  const schemaFiles = readdirSync(schemasDir)
    .filter((filename) => filename.endsWith(".schema.json"))
    .sort((left, right) => {
      const leftExported = exportedSchemas.has(left) ? 0 : 1;
      const rightExported = exportedSchemas.has(right) ? 0 : 1;
      return leftExported - rightExported || left.localeCompare(right);
    });

  return [
    "# Lycium contract schema reference",
    "",
    "<!-- Generated by packages/contracts/scripts/generate-schema-docs.mjs. Do not edit by hand. -->",
    "",
    "Lycium contracts are schema-first. These docs are generated from the JSON schemas in `packages/contracts/schemas` so the reference stays aligned with runtime validation and fixtures.",
    "",
    "## How to regenerate",
    "",
    "```bash",
    "corepack pnpm --filter @lycium/contracts docs:schemas",
    "```",
    "",
    "To verify docs are current without writing files:",
    "",
    "```bash",
    "corepack pnpm --filter @lycium/contracts docs:schemas:check",
    "```",
    "",
    "## Public schema exports",
    "",
    ...schemaFiles.map((filename) => `- \`@lycium/contracts/schemas/${filename}\``),
    "",
    ...schemaFiles.map((filename) => docForSchema(filename, exportedSchemas)),
  ].join("\n");
}

const nextMarkdown = generateMarkdown();
const checkOnly = process.argv.includes("--check");
if (checkOnly) {
  const current = readFileSync(docsPath, "utf8");
  if (current !== nextMarkdown) {
    console.error(`Schema docs are out of date: ${relative(repoRoot, docsPath)}`);
    console.error("Run: corepack pnpm --filter @lycium/contracts docs:schemas");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(docsPath), { recursive: true });
  writeFileSync(docsPath, nextMarkdown, "utf8");
}
